#!/usr/bin/env python3
"""Draws the dancing chibi (an original character) for the fetch card and
writes quickshell/DancerFrames.js.

The art is pixels, printed with half-block characters (each text cell is
two pixels, top and bottom, in one colour). Edit the pixel rows below and
run:  python3 tools/make-dancer.py

Codes: H hair, D dress, S skin, E eyes, B blush, R ribbons, L shoes,
'.' nothing. Hair and dress take the theme's colour; the rest are fixed.
"""
import json
from pathlib import Path

W, H = 20, 24

HEAD = [
    "....................",  # 0  (hands are drawn separately)
    "....................",  # 1
    "........HHHH........",  # 2
    "......HHHHHHHH......",  # 3
    ".....HHHHHHHHHH.....",  # 4
    "....HHHHHHHHHHHH....",  # 5
    "...RHHHHHHHHHHHHR...",  # 6  ribbons
    "...HHHHHHHHHHHHHH...",  # 7  bangs
    "...HHSSSSHHSSSSHH...",  # 8  parting
    "..HHHSSSSSSSSSSHHH..",  # 9
    "..HHHSEESSSSEESHHH..",  # 10 eyes (one cell tall)
    "..HHHSEESSSSEESHHH..",  # 11
    "..HHHBBSSSSSSBBHHH..",  # 12 blush
    ".HHH.SSSS..SSSS.HHH.",  # 13 mouth (a gap)
    ".HHH..SSSSSSSS..HHH.",  # 14
    ".HH..............HH.",  # 15 twin tails
    "HHH..............HHH",  # 16
    "HH................HH",  # 17
    "HH................HH",  # 18
    "H..................H",  # 19
]

BODY = [
    "......DDDDDD......",    # 15
    ".....DDDRRDDD.....",    # 16 ribbon
    ".....DDDDDDDD.....",    # 17
    "....DDDDDDDDDD....",    # 18
    "...DDDDDDDDDDDD...",    # 19
    "..DDDDDDDDDDDDDD..",    # 20
    "......SS..SS......",    # 21
    "......SS..SS......",    # 22
    ".....LLL..LLL.....",    # 23
]

STEP = [                     # knees out, on the off-beat
    ".....SS....SS.....",
    ".....SS....SS.....",
    "....LLL....LLL....",
]

HANDS = {
    "out": ["SS................SS",   # palms out, wide, like ears
            "SS................SS",
            ".S................S.",
            "..S..............S..",
            "...S............S...",
            "....S..........S...."],
    "in":  ["....SS........SS....",   # flapped in, over the head
            "....SS........SS....",
            "....S..........S....",
            "....S..........S....",
            "....S..........S....",
            "....S..........S...."],
}

PRIORITY = "EBRSLDH"   # when a cell's two pixels differ, the earlier wins


def frame(hands, hip, step):
    g = [list(r) for r in HEAD] + [list("." * W) for _ in range(H - len(HEAD))]
    for y, row in enumerate(HANDS[hands]):
        for x, c in enumerate(row):
            if c != "." and g[y][x] == ".":
                g[y][x] = c
    body = BODY[:6] + (STEP if step else BODY[6:])
    for i, row in enumerate(body):
        for x, c in enumerate(row):
            xx = x + 1 + hip
            if c != "." and 0 <= xx < W:
                g[15 + i][xx] = c
    return ["".join(r) for r in g]


def cells(px):
    chars, codes = [], []
    for y in range(0, len(px), 2):
        top, bot = px[y], px[y + 1]
        cr, co = "", ""
        for t, b in zip(top, bot):
            if t == "." and b == ".":
                cr, co = cr + " ", co + "."
            elif b == ".":
                cr, co = cr + "▀", co + t
            elif t == ".":
                cr, co = cr + "▄", co + b
            else:
                cr += "█"
                co += t if PRIORITY.index(t) <= PRIORITY.index(b) else b
        chars.append(cr)
        codes.append(co)
    return {"chars": chars, "codes": codes}


# The dance: hips left with palms out, centre with palms in, hips right
# with palms out, centre again.
FRAMES = [frame("out", -1, False), frame("in", 0, True),
          frame("out", 1, False), frame("in", 0, True)]

if __name__ == "__main__":
    for f in FRAMES:
        assert len(f) == H and all(len(r) == W for r in f)
    out = Path(__file__).resolve().parent.parent / "quickshell" / "DancerFrames.js"
    out.write_text(
        "// Generated by tools/make-dancer.py; edit the pixels there.\n"
        ".pragma library\n\n"
        f"var frames = {json.dumps([cells(f) for f in FRAMES], ensure_ascii=False, indent=1)};\n")
    print(f"wrote {out}")
